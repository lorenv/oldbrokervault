// Load PDF background template based on user preference
async function loadPdfBackgroundTemplate(templateName?: string): Promise<pdfLib.PDFDocument | null> {
  try {
    if (!templateName || templateName === 'none') {
      console.log("No background template requested");
      return null;
    }
    
    const templateFilename = `${templateName}.pdf`;
    const backgroundPath = path.resolve(process.cwd(), 'pdf-templates', templateFilename);
    
    if (!fs.existsSync(backgroundPath)) {
      console.log("PDF background template not found at:", backgroundPath);
      // Fallback to classic template
      const fallbackPath = path.resolve(process.cwd(), 'pdf-templates', 'classic.pdf');
      if (fs.existsSync(fallbackPath)) {
        const fallbackBytes = fs.readFileSync(fallbackPath);
        const fallbackDoc = await pdfLib.PDFDocument.load(fallbackBytes);
        console.log("Using fallback classic template");
        return fallbackDoc;
      }
      return null;
    }
    
    const backgroundBytes = fs.readFileSync(backgroundPath);
    const backgroundDoc = await pdfLib.PDFDocument.load(backgroundBytes);
    
    console.log(`Successfully loaded PDF background template: ${templateName}`);
    return backgroundDoc;
  } catch (error) {
    console.error("Failed to load PDF background template:", error);
    return null;
  }
}

// Apply background template to pages after the first page
async function applyBackgroundToPages(originalPdfBuffer: Buffer, backgroundTemplate: pdfLib.PDFDocument): Promise<Buffer> {
  try {
    // Load the original PDF generated by PDFKit
    const originalDoc = await pdfLib.PDFDocument.load(originalPdfBuffer);
    const originalPages = originalDoc.getPages();
    
    if (originalPages.length <= 1) {
      console.log("PDF has only one page, no background needed");
      return originalPdfBuffer;
    }
    
    // Get the background page from the template
    const backgroundPages = backgroundTemplate.getPages();
    if (backgroundPages.length === 0) {
      console.log("Background template has no pages");
      return originalPdfBuffer;
    }
    
    console.log("Background template loaded with", backgroundPages.length, "pages");
    
    // Create a new PDF document for the final result
    const finalDoc = await pdfLib.PDFDocument.create();
    
    // Copy first page without background (title page)
    console.log("Copying first page without background...");
    const [firstPage] = await finalDoc.copyPages(originalDoc, [0]);
    finalDoc.addPage(firstPage);
    
    // ULTRA PERFORMANCE OPTIMIZATION: Pre-embed background template once for all pages
    console.log("Pre-embedding background template for maximum performance...");
    const templateEmbedStart = Date.now();
    const [backgroundPageCopy] = await finalDoc.copyPages(backgroundTemplate, [0]);
    const backgroundForm = await finalDoc.embedPage(backgroundPageCopy);
    console.log("Template embed time:", Date.now() - templateEmbedStart + "ms");
    
    // Process remaining pages with optimized background template
    console.log(`Processing ${originalPages.length - 1} pages with pre-embedded background...`);
    const pageProcessStart = Date.now();
    
    for (let i = 1; i < originalPages.length; i++) {
      try {
        // Create new page with standard letter size
        const newPage = finalDoc.addPage([612, 792]);
        
        // Draw pre-embedded background template (MUCH faster than copying each time)
        newPage.drawPage(backgroundForm, {
          x: 0,
          y: 0,
          width: newPage.getWidth(),
          height: newPage.getHeight()
        });
        
        // Get the original content page
        const originalContentPage = originalPages[i];
        
        // Optimized content area with 0.5-inch margins
        const marginSize = 36;
        const pageWidth = newPage.getWidth();
        const pageHeight = newPage.getHeight();
        const contentWidth = pageWidth - (2 * marginSize);
        const contentHeight = pageHeight - (2 * marginSize);
        
        // Draw semi-transparent content background
        newPage.drawRectangle({
          x: marginSize,
          y: marginSize,
          width: contentWidth,
          height: contentHeight,
          color: pdfLib.rgb(1, 1, 1),
          opacity: 0.8
        });
        
        // Embed content page efficiently
        const contentForm = await finalDoc.embedPage(originalContentPage);
        
        // Scale content to fit within margins
        const scaleX = contentWidth / originalContentPage.getWidth();
        const scaleY = contentHeight / originalContentPage.getHeight();
        const scale = Math.min(scaleX, scaleY, 1.0);
        
        const scaledWidth = originalContentPage.getWidth() * scale;
        const scaledHeight = originalContentPage.getHeight() * scale;
        
        // Center content within margins
        const xOffset = marginSize + (contentWidth - scaledWidth) / 2;
        const yOffset = marginSize + (contentHeight - scaledHeight) / 2;
        
        // Draw optimized content
        newPage.drawPage(contentForm, {
          x: xOffset,
          y: yOffset,
          width: scaledWidth,
          height: scaledHeight
        });
        
        if (i % 5 === 0) {
          console.log(`Processed ${i} of ${originalPages.length - 1} pages with background...`);
        }
        
      } catch (pageError) {
        console.error(`Error processing page ${i + 1}:`, pageError);
        // Fallback: add original page without background
        const [originalPage] = await finalDoc.copyPages(originalDoc, [i]);
        finalDoc.addPage(originalPage);
      }
    }
    
    // Save the final PDF with backgrounds applied
    const finalPdfBytes = await finalDoc.save();
    console.log(`Background template applied to ${originalPages.length - 1} content pages`);
    
    return Buffer.from(finalPdfBytes);
    
  } catch (error) {
    console.error("Error in applyBackgroundToPages:", error);
    // Return original PDF if background application fails
    return originalPdfBuffer;
  }
}

// Helper function to create a cropped image based on position data
async function createCroppedImageBuffer(imagePath: string, position: { x: number; y: number }, bannerWidth: number, bannerHeight: number): Promise<Buffer | null> {
  try {
    // Read the original image to get its dimensions
    const imageBuffer = fs.readFileSync(imagePath);
    const metadata = await sharp(imageBuffer).metadata();
    
    if (!metadata.width || !metadata.height) {
      console.log("Could not get image dimensions for cropping");
      return null;
    }
    
    // Calculate the crop area based on the position (x, y are percentages)
    // We want to create a banner with the specified aspect ratio
    const targetAspectRatio = bannerWidth / bannerHeight;
    const originalAspectRatio = metadata.width / metadata.height;
    
    let cropWidth, cropHeight, cropLeft, cropTop;
    
    if (originalAspectRatio > targetAspectRatio) {
      // Image is wider than target ratio - crop horizontally
      cropHeight = metadata.height;
      cropWidth = Math.round(cropHeight * targetAspectRatio);
      
      // Use x position to determine horizontal crop position
      const maxLeft = metadata.width - cropWidth;
      cropLeft = Math.round((position.x / 100) * maxLeft);
      cropTop = Math.round((position.y / 100) * (metadata.height - cropHeight));
    } else {
      // Image is taller than target ratio - crop vertically
      cropWidth = metadata.width;
      cropHeight = Math.round(cropWidth / targetAspectRatio);
      
      // Use y position to determine vertical crop position
      const maxTop = metadata.height - cropHeight;
      cropTop = Math.round((position.y / 100) * maxTop);
      cropLeft = Math.round((position.x / 100) * (metadata.width - cropWidth));
    }
    
    // Ensure crop values are within bounds
    cropLeft = Math.max(0, Math.min(cropLeft, metadata.width - cropWidth));
    cropTop = Math.max(0, Math.min(cropTop, metadata.height - cropHeight));
    
    console.log(`Cropping image: ${cropWidth}x${cropHeight} at ${cropLeft},${cropTop} from ${metadata.width}x${metadata.height}`);
    
    // Create cropped and resized buffer
    const croppedBuffer = await sharp(imageBuffer)
      .extract({ left: cropLeft, top: cropTop, width: cropWidth, height: cropHeight })
      .resize(Math.round(bannerWidth), Math.round(bannerHeight))
      .jpeg({ quality: 90 })
      .toBuffer();
    
    return croppedBuffer;
  } catch (error) {
    console.error("Error creating cropped image:", error);
    return null;
  }
}

// Helper function to download and cache external images
async function downloadAndCacheImage(imageUrl: string): Promise<string | null> {
  try {
    console.log("Downloading external image:", imageUrl);
    
    // Create cache directory if it doesn't exist
    const cacheDir = path.resolve(process.cwd(), 'private', 'image-cache');
    if (!fs.existsSync(cacheDir)) {
      fs.mkdirSync(cacheDir, { recursive: true });
    }
    
    // Generate cache filename based on URL hash
    const hash = crypto.createHash('md5').update(imageUrl).digest('hex');
    const extension = imageUrl.includes('.jpg') || imageUrl.includes('jpg') ? '.jpg' : 
                     imageUrl.includes('.png') || imageUrl.includes('png') ? '.png' : '.jpg';
    const cachedPath = path.join(cacheDir, `${hash}${extension}`);
    
    // Check if already cached
    if (fs.existsSync(cachedPath)) {
      console.log("Using cached image:", cachedPath);
      return cachedPath;
    }
    
    // Download the image
    const response = await fetch(imageUrl, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36'
      }
    });
    
    if (!response.ok) {
      console.error("Failed to download image:", response.status, response.statusText);
      return null;
    }
    
    const buffer = Buffer.from(await response.arrayBuffer());
    fs.writeFileSync(cachedPath, buffer);
    console.log("Successfully cached image:", cachedPath);
    
    return cachedPath;
  } catch (error) {
    console.error("Error downloading image:", error);
    return null;
  }
}

// Helper function to resolve image paths correctly
function resolveImagePath(imagePath: string, documentId?: number): string {
  if (!imagePath) return '';
  
  // If it's already an absolute path, return as is
  if (path.isAbsolute(imagePath)) {
    return imagePath;
  }
  
  // If it starts with '/', assume it's relative to the project root public folder
  if (imagePath.startsWith('/')) {
    const publicPath = path.resolve(process.cwd(), 'public', imagePath.substring(1));
    console.log(`Resolving path: ${imagePath} -> ${publicPath}`);
    return publicPath;
  }
  
  // If it starts with 'attached_assets/', resolve relative to project root
  if (imagePath.startsWith('attached_assets/')) {
    return path.resolve(process.cwd(), imagePath);
  }
  
  // For other cases, try multiple locations including document-specific subdirectories
  const possiblePaths = [
    // Try attached_assets folder first
    path.resolve(process.cwd(), 'attached_assets', imagePath),
    // Try public folder directly
    path.resolve(process.cwd(), 'public', imagePath),
    // Try business-images with document ID subdirectory
    documentId ? path.resolve(process.cwd(), 'public', 'business-images', documentId.toString(), path.basename(imagePath)) : null,
    // Try business-images without document ID
    path.resolve(process.cwd(), 'public', 'business-images', imagePath),
    // Try logos folder
    path.resolve(process.cwd(), 'public', 'logos', imagePath),
    // Try images folder
    path.resolve(process.cwd(), 'public', 'images', imagePath),
    // Try with just the filename in business-images
    path.resolve(process.cwd(), 'public', 'business-images', path.basename(imagePath)),
    // Try with just the filename in logos
    path.resolve(process.cwd(), 'public', 'logos', path.basename(imagePath))
  ].filter(Boolean);
  
  for (const possiblePath of possiblePaths) {
    if (fs.existsSync(possiblePath)) {
      console.log(`Found image at: ${possiblePath}`);
      return possiblePath;
    }
  }
  
  console.log(`Image not found in any location: ${imagePath}`);
  // Default to public folder if file doesn't exist yet
  return path.resolve(process.cwd(), 'public', imagePath);
}



// Simple helper functions to read image dimensions from file headers
function getJpegDimensions(buffer: Buffer): { width: number; height: number } | null {
  try {
    // JPEG files start with FF D8
    if (buffer[0] !== 0xFF || buffer[1] !== 0xD8) return null;
    
    let offset = 2;
    while (offset < buffer.length) {
      // Look for SOF markers (Start of Frame)
      if (buffer[offset] === 0xFF && (buffer[offset + 1] === 0xC0 || buffer[offset + 1] === 0xC2)) {
        // SOF found, dimensions are at offset + 5 (height) and offset + 7 (width)
        const height = buffer.readUInt16BE(offset + 5);
        const width = buffer.readUInt16BE(offset + 7);
        return { width, height };
      }
      
      // Skip to next marker
      if (buffer[offset] === 0xFF) {
        const segmentLength = buffer.readUInt16BE(offset + 2);
        offset += segmentLength + 2;
      } else {
        offset++;
      }
    }
  } catch (e) {
    // Return null if parsing fails
  }
  return null;
}

function getPngDimensions(buffer: Buffer): { width: number; height: number } | null {
  try {
    // PNG files start with 8-byte signature
    const pngSignature = Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]);
    if (!buffer.subarray(0, 8).equals(pngSignature)) return null;
    
    // IHDR chunk starts at byte 8, dimensions are at bytes 16-19 (width) and 20-23 (height)
    const width = buffer.readUInt32BE(16);
    const height = buffer.readUInt32BE(20);
    return { width, height };
  } catch (e) {
    // Return null if parsing fails
  }
  return null;
}

// Helper function to safely stringify any value
function safeStringify(value: any): string {
  if (value === null || value === undefined) {
    return '';
  }
  if (typeof value === 'string') {
    return value;
  }
  if (typeof value === 'object') {
    return JSON.stringify(value);
  }
  return String(value);
}

